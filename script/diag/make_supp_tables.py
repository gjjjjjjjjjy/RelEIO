#!/usr/bin/env python3
"""Supplementary tables of the paper, generated from the committed per-run CSVs. Read-only on the data.

Inputs (records directory, see script/_layout.py):
  round4_all_attribution_*.csv      every run of the round 4 main matrix (640) with outcome and numerical probe
  deio_se3_round4_steps_*.csv       every completed run re-scored under rules A-D (script/diag/deio_se3_eval.py)
  round4_main_table_se3.csv         per condition and arm (script/diag/round4_reliability.py)
  hardware_*_details_*.csv          H100 / H200 / L40S replication runs
  imu_bias_cross_system_pinned_*.csv  the common-gyroscope-bias runs of DEIO and SuperEIO (valid, CPU-pinned batch)
Outputs: LaTeX tables supp_*.tex in the tables directory, and on stdout every number that the main text quotes from these
files, so the text can be checked against the data.

Rules (Sec. III-D of the manuscript): A = DEIO's evaluation code (Sim(3) fitted on the first 1000 poses, all poses
on UZH-FPV, 1 s matching); B = A with 20 ms matching; C = B fitted on all poses; D = C without scale (SE(3)), the main rule.
Medians use linear interpolation. Intervals: Wilson, Newcombe hybrid score (method 10), MOVER for differences of
differences, as in script/diag/round4_analysis.py, whose functions are reused here.

  python3 script/diag/make_supp_tables.py
"""
import collections
import csv
import glob
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.dirname(HERE))
import _layout  # noqa: E402
import round4_analysis as R4  # noqa: E402
import precision_pilot as P  # noqa: E402

AN, OUT = _layout.RECORDS, _layout.TABLES

SEQ = collections.OrderedDict([
    ("tumvie/mocap-3d-trans", "TUM-VIE mocap-3d-trans"),
    ("hku/vicon_dark1", "HKU vicon\\_dark1"),
    ("fpv/indoor_forward_3", "UZH-FPV indoor\\_forward\\_3"),
    ("vector/corner_slow1", "VECtor corner\\_slow1"),
    ("vector/desk_normal1", "VECtor desk\\_normal1"),
    ("rpgdavis/shapes_6dof", "DAVIS240C shapes\\_6dof"),
    ("rpgdavis/poster_6dof", "DAVIS240C poster\\_6dof"),
    ("rpgdavis/boxes_6dof", "DAVIS240C boxes\\_6dof"),
])
CELL = collections.OrderedDict([("clean", "clean"), ("keep:0.1", "$\\rho=0.1$"),
                                ("tq:10000", "$\\tau=10$\\,ms"), ("patch:16", "$P=16$")])
ARMS = ("default", "no_tf32_override")


def one(pattern):
    f = sorted(glob.glob(os.path.join(AN, pattern)))
    if len(f) != 1:
        sys.exit("expected one file for %s, found %d" % (pattern, len(f)))
    return f[0]


def rows(path):
    with open(path) as fh:
        return list(csv.DictReader(fh))


def med(v):
    v = sorted(v)
    return R4.q(v, 0.5) if v else math.nan


def pct(x):
    """MPE in percent, two significant decimals below 10, otherwise three significant figures."""
    if x != x:
        return "--"
    if x < 10:
        return "%.2f" % x
    return "%.3g" % x if x < 1000 else "%d" % round(x)


def half_up(x):
    """Round to an integer with halves away from zero (12.5 -> 13), as the text of the paper does."""
    return int(math.copysign(math.floor(abs(x) + 0.5), x))


def ci(t):
    d, lo, hi = t
    return "$%+d$ [$%+d$, $%+d$]" % (half_up(100 * d), half_up(100 * lo), half_up(100 * hi))


def write(name, body):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w") as fh:
        fh.write("% generated by script/diag/make_supp_tables.py -- do not edit by hand\n" + body)
    print("wrote %s" % _layout.rel(os.path.join(OUT, name)))


# ------------------------------------------------------------------------------------------------
att = rows(one("round4_all_attribution_*.csv"))
steps = rows(one("deio_se3_round4_steps_*.csv"))
se3tab = rows(os.path.join(AN, "round4_main_table_se3.csv"))
assert len(att) == 640, len(att)
fail = collections.Counter()
n = collections.Counter()
for r in att:
    k = (r["scene"], r["cell"], r["arm"])
    n[k] += 1
    fail[k] += r["category"] == "numerical_failure"
assert set(n.values()) == {10}, "every condition and arm must have 10 runs"
cats = collections.Counter(r["category"] for r in att)
assert set(cats) <= {"completed", "numerical_failure"}, cats

# ---- Table: crashes per condition, with pooled rows -------------------------------------------
print("\n== crashes")
lines = []
for s, sname in SEQ.items():
    for c, cname in CELL.items():
        kd, ko = fail[(s, c, "default")], fail[(s, c, "no_tf32_override")]
        lines.append("%s & %s & %d/10 & %d/10 & %s \\\\" % (sname if c == "clean" else "", cname, kd, ko,
                                                            ci(R4.newcombe(kd, 10, ko, 10))))
    lines.append("\\addlinespace")
pooled = []
for c, cname in CELL.items():
    kd = sum(fail[(s, c, "default")] for s in SEQ)
    ko = sum(fail[(s, c, "no_tf32_override")] for s in SEQ)
    pooled.append("all sequences & %s & %d/80 & %d/80 & %s \\\\" % (cname, kd, ko, ci(R4.newcombe(kd, 80, ko, 80))))
    print("pooled %-9s default %2d/80  removed %d/80" % (c, kd, ko))
kd = sum(fail[(s, c, "default")] for s in SEQ for c in CELL)
ko = sum(fail[(s, c, "no_tf32_override")] for s in SEQ for c in CELL)
lo, hi = P.wilson(kd, 320)
print("total default %d/320 Wilson [%.1f, %.1f]%%; removed %d/320 upper %.1f%%; diff %s"
      % (kd, 100 * lo, 100 * hi, ko, 100 * P.wilson(ko, 320)[1], ci(R4.newcombe(kd, 320, ko, 320))))
pooled.append("all & all & %d/320 & %d/320 & %s \\\\" % (kd, ko, ci(R4.newcombe(kd, 320, ko, 320))))
write("supp_crashes.tex", r"""\begin{table}[H]
  \centering
  \caption{Numerical failures in the round-4 main matrix per sequence and condition, ten runs per arm (seeds
  2000--2009). Difference: default minus override removed, in percentage points, with Newcombe's $95\%$ interval.
  Pooled rows weight every condition equally.}
  \label{stab:crashes}
  \footnotesize
  \begin{tabular}{@{}llccc@{}}
    \toprule
    Sequence & Condition & Default & Override removed & Difference [$95\%$ CI] \\
    \midrule
""" + "\n".join("    " + x for x in lines[:-1]) + "\n    \\midrule\n" + "\n".join("    " + x for x in pooled) + r"""
    \bottomrule
  \end{tabular}
\end{table}
""")

# ---- Table: interactions (24 pre-specified groups) --------------------------------------------
print("\n== interactions (difference at level minus difference on clean)")
lines, excl = [], []
for s, sname in SEQ.items():
    dc = R4.newcombe(fail[(s, "clean", "default")], 10, fail[(s, "clean", "no_tf32_override")], 10)
    for j, (ax, c) in enumerate(R4.AXES):
        dl = R4.newcombe(fail[(s, c, "default")], 10, fail[(s, c, "no_tf32_override")], 10)
        it = R4.mover(dl, dc)
        mark = it[1] > 0 or it[2] < 0
        if mark:
            excl.append((s, c, it))
        lines.append("%s & %s & %s & %s & %s%s \\\\" % (sname if j == 0 else "", CELL[c], ci(dl), ci(dc),
                                                       ci(it), "$^{*}$" if mark else ""))
    lines.append("\\addlinespace")
for s, c, it in excl:
    print("excludes 0: %s %s %s" % (s, c, ci(it)))
print("groups excluding 0: %d of 24" % len(excl))
write("supp_interactions.tex", r"""\begin{table}[H]
  \centering
  \caption{Interaction between the numerical arm and each stress axis, per sequence (24 groups fixed
  before the run, all reported). Columns give the difference between arms (percentage points, Newcombe $95\%$
  interval) at the strongest level and on clean input, and their difference with the MOVER $95\%$ interval.
  $^{*}$: interval excludes zero.}
  \label{stab:interactions}
  \footnotesize
  \begin{tabular}{@{}llccc@{}}
    \toprule
    Sequence & Level & Difference at level & Difference on clean & Interaction \\
    \midrule
""" + "\n".join("    " + x for x in lines[:-1]) + r"""
    \bottomrule
  \end{tabular}
\end{table}
""")

# ---- Table: where the failures start ----------------------------------------------------------
print("\n== crash location")


def location(rs):
    f = [r for r in rs if r["outcome"].startswith("numerical_failure")]
    c = [r for r in rs if r["outcome"] == "completed"]
    flag = lambda r: (int(r["chol_flags"] or 0) > 0)  # noqa: E731
    return {
        "fail": len(f), "runs": len(rs),
        "ba": sum(r["first_where"] == "fastba.BA(out)" for r in f),
        "noimu": sum(r["first_imu_enabled"] == "False" for r in f),
        "chol_f": sum(flag(r) for r in f),
        "chol_finite": sum(flag(r) and r["chol_first_S_finite"] == "True" for r in f),
        "chol_first": sum(r["chol_vs_detection"] == "chol_first" for r in f),
        "chol_c": sum(flag(r) for r in c), "comp": len(c),
    }


hw = [("RTX 4090, main matrix (driver 570)", att)]
for pat, name in [("hardware_l40s_*", "L40S (driver 595)"), ("hardware_h200_*", "H200 (driver 570)"),
                  ("hardware_h100_*", "H100 (driver 570)")]:
    hw.append((name, rows(one(pat + ".csv"))))
lines = []
for name, rs in hw:
    L = location([r for r in rs if r["arm"] == "default"])
    Lall = location(rs)
    print("%-36s %s; Cholesky flags in completed runs of both arms: %d/%d"
          % (name, L, Lall["chol_c"], Lall["comp"]))
    lines.append("%s & %d/%d & %d & %d & %d & %d & %d & %d/%d \\\\" % (
        name, L["fail"], L["runs"], L["ba"], L["noimu"], L["chol_f"], L["chol_finite"], L["chol_first"],
        Lall["chol_c"], Lall["comp"]))
write("supp_location.tex", r"""\begin{table}[H]
  \centering
  \caption{Where the crashes start (container default arm). BA: first non-finite value detected at the output of
  the visual bundle adjustment; no IMU: before the visual-inertial alignment had added IMU factors; Cholesky: the
  factorization of the dense Schur complement reported a failure; finite $\mathbf{S}$: at its first report the
  Schur complement was still finite; before detection: the first report preceded the first detection. Last
  column: completed runs of both arms with any Cholesky report.}
  \label{stab:location}
  \footnotesize
  \begin{tabular}{@{}lccccccc@{}}
    \toprule
    Machine & Crashes & BA & No IMU & Cholesky & Finite $\mathbf{S}$ & Before detection & Cholesky, completed \\
    \midrule
""" + "\n".join("    " + x for x in lines) + r"""
    \bottomrule
  \end{tabular}
\end{table}
""")

# ---- Table: accuracy per condition and arm (64 rows as 32 x 2) -------------------------------
print("\n== accuracy per condition")
t = {(r["sequence"], r["cell"], r["setting"]): r for r in se3tab}
assert len(t) == 64
within10 = collections.Counter()
scores = collections.defaultdict(lambda: {"D": [], "A": []})   # medians from the per-run scores: the derived
for r in rows(one("deio_se3_round4_steps_*.csv")):             # table holds them to three decimals only
    k = (r["scene"], r["cell"], r["arm"])
    scores[k]["D"].append(float(r["se3_all"]))
    scores[k]["A"].append(float(r["deio_rule"]))
    if float(r["se3_all"]) <= 10:
        within10[k] += 1
lines = []
for s, sname in SEQ.items():
    for c, cname in CELL.items():
        cells = []
        for a in ARMS:
            r = t[(s, c, a)]
            cells += ["%d" % within10[(s, c, a)], "%s" % r["completed_se3_le_100"],
                      pct(med(scores[(s, c, a)]["D"])), pct(med(scores[(s, c, a)]["A"])),
                      r["sim3_scale_below_0p5"]]
            for rule, col in (("D", "median_se3_mpe"), ("A", "median_rule_a_mpe")):
                assert not r[col] or abs(med(scores[(s, c, a)][rule]) - float(r[col])) < 6e-4, (s, c, a, rule)
        lines.append("%s & %s & %s \\\\" % (sname if c == "clean" else "", cname, " & ".join(cells)))
    lines.append("\\addlinespace")
for a in ARMS:
    print("%s: per sequence within 100%% (SE3): %s" % (a, ", ".join(
        "%s %d" % (s.split("/")[1], sum(int(t[(s, c, a)]["completed_se3_le_100"]) for c in CELL)) for s in SEQ)))
    print("%s: clean medians SE3 / A: %s" % (a, ", ".join(
        "%s %s/%s" % (s.split("/")[1], t[(s, "clean", a)]["median_se3_mpe"], t[(s, "clean", a)]["median_rule_a_mpe"])
        for s in SEQ)))
write("supp_accuracy.tex", r"""\begin{table}[H]
  \centering
  \caption{Accuracy per input condition and arm, ten runs each. $\le$10\%, $\le$100\%: runs completed with a
  rule~D error at most $10\%$ or $100\%$ of the path length (crashes count as not within); D, A: median MPE (\%)
  of completed runs under rules~D and~A;
  $s<0.5$: completed runs with a small fitted Sim(3) scale (below $0.5$), which accompanies a collapsed fit but
  does not by itself establish one (Section~\ref{ss:simfit}).}
  \label{stab:accuracy}
  \footnotesize
  \setlength{\tabcolsep}{4pt}
  \begin{tabular}{@{}llcccccccccc@{}}
    \toprule
    & & \multicolumn{5}{c}{Container default} & \multicolumn{5}{c@{}}{Override removed} \\
    \cmidrule(lr){3-7}\cmidrule(l){8-12}
    Sequence & Condition & $\le$10\% & $\le$100\% & D & A & $s<0.5$ & $\le$10\% & $\le$100\% & D & A & $s<0.5$ \\
    \midrule
""" + "\n".join("    " + x for x in lines[:-1]) + r"""
    \bottomrule
  \end{tabular}
\end{table}
""")

# ---- Table: scoring rules A-D ------------------------------------------------------------------
print("\n== scoring rules")
RULES = [("A", "deio_rule", "Sim(3), first 1000 poses$^{a}$, 1\\,s matching (DEIO's code)"),
         ("B", "sim3_1000_20ms", "Sim(3), first 1000 poses$^{a}$, 20\\,ms matching"),
         ("C", "sim3_all", "Sim(3), all poses, 20\\,ms matching"),
         ("D", "se3_all", "SE(3), all poses, 20\\,ms matching (main)")]
assert len(steps) == 592 and all(r["score"] == "ok" for r in steps), "all 592 completed runs must be scored"
lines = []
for key, col, desc in RULES:
    cells = []
    for a in ARMS:
        v = [float(r[col]) for r in steps if r["arm"] == a]
        cnt = [sum(x <= e for x in v) for e in (1, 10, 100)]
        above = sum(x > 100 for x in v)
        cells += ["%d" % x for x in cnt] + ["%d" % above]
        print("rule %s %-16s completed %d: <=1%% %d, <=10%% %d, <=100%% %d (of 320), >100%% %d"
              % (key, a, len(v), cnt[0], cnt[1], cnt[2], above))
    lines.append("%s & %s & %s \\\\" % (key, desc, " & ".join(cells)))
write("supp_rules.tex", r"""\begin{table}[H]
  \centering
  \caption{The same 592 completed runs under four scoring rules that change one step at a time. Counts of runs
  completed within $1\%$, $10\%$, and $100\%$ of the path length (out of 320 runs per arm; crashes count as not
  within), and completed runs above $100\%$.}
  \label{stab:rules}
  \footnotesize
  \setlength{\tabcolsep}{4pt}
  \begin{tabular}{@{}llcccccccc@{}}
    \toprule
    & & \multicolumn{4}{c}{Container default} & \multicolumn{4}{c@{}}{Override removed} \\
    \cmidrule(lr){3-6}\cmidrule(l){7-10}
    Rule & Alignment and matching & $\le$1\% & $\le$10\% & $\le$100\% & $>$100\% & $\le$1\% & $\le$10\% & $\le$100\% & $>$100\% \\
    \midrule
""" + "\n".join("    " + x for x in lines) + r"""
    \bottomrule
  \end{tabular}\\[2pt]
  \footnotesize $^{a}$All poses on UZH-FPV, as in DEIO's evaluation code.
\end{table}
""")

# A -> B (matching only) and the paired comparison of A and D, as quoted in the main text
ab = [abs(float(r["deio_rule"]) - float(r["sim3_1000_20ms"])) for r in steps]
flips = sum((float(r["deio_rule"]) <= e) != (float(r["sim3_1000_20ms"]) <= e) for r in steps for e in (1, 10, 100))
print("A->B: %d runs changed (%s), max %.4f pp, tolerance crossings %d" % (
    sum(x > 0 for x in ab), sorted({r["scene"] for r, x in zip(steps, ab) if x > 0}), max(ab), flips))
A100 = {r["run"] for r in steps if float(r["deio_rule"]) > 100}
D100 = {r["run"] for r in steps if float(r["se3_all"]) > 100}
print("A above 100%%: %d, all within D above 100%% (%d): %s" % (len(A100), len(D100), A100 <= D100))
for a in ARMS:
    g = [r for r in steps if r["arm"] == a]
    for e in (1, 10, 100):
        ad = sum(float(r["deio_rule"]) <= e < float(r["se3_all"]) for r in g)
        da = sum(float(r["se3_all"]) <= e < float(r["deio_rule"]) for r in g)
        print("%s eps %d%%: pass A fail D %d, pass D fail A %d" % (a, e, ad, da))

# ---- Table: common gyroscope bias, every run -------------------------------------------------
print("\n== gyroscope bias")
bias = rows(one("imu_bias_cross_system_pinned_*.csv"))
assert len(bias) == 80 and all(r["status"] == "completed" for r in bias), "80 completed runs expected"
g = collections.defaultdict(list)
for r in bias:
    g[(r["system"], r["seq"], r["cond"])].append(r)
lines = []
for sysname in ("DEIO", "SuperEIO"):
    for seq in ("boxes_6dof", "poster_6dof"):
        for cond, cname in (("clean", "clean"), ("gbias", "bias")):
            rs = g[(sysname, seq, cond)]
            assert len(rs) == 10
            v = sorted(float(r["se3_W"]) for r in rs)
            ratio = med([float(r["dist_ratio_1s"]) for r in rs if r["dist_ratio_1s"]])
            print("%-8s %-11s %-5s median %s [%s, %s]; 1 s distance ratio median %.2f"
                  % (sysname, seq, cond, pct(med(v)), pct(v[0]), pct(v[-1]), ratio))
            lines.append("%s & %s & %s & %s & %.2f \\\\" % (
                sysname if (seq, cond) == ("boxes_6dof", "clean") else "",
                seq.replace("_", "\\_") if cond == "clean" else "", cname, ", ".join(pct(x) for x in v), ratio))
        lines.append("\\addlinespace")
write("supp_bias.tex", r"""\begin{table}[H]
  \centering
  \caption{Common gyroscope bias $(+5, -5, +5)^\circ$/s: rule~D error (\%) of every run on the common time window,
  sorted, and the median ratio of travelled distance over one-second windows (estimate / ground truth).}
  \label{stab:bias}
  \footnotesize
  \begin{tabular}{@{}lllp{0.52\linewidth}c@{}}
    \toprule
    System & Sequence & Input & Rule~D error of the ten runs (\%) & Distance ratio \\
    \midrule
""" + "\n".join("    " + x for x in lines[:-1]) + r"""
    \bottomrule
  \end{tabular}
\end{table}
""")
