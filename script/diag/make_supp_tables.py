def one(pattern):
    f = sorted(glob.glob(os.path.join(AN, pattern)))
    if len(f) != 1:
        sys.exit("expected one file for %s, found %d" % (pattern, len(f)))
    return f[0]


def rows(path):
    with open(path) as fh:
        return list(csv.DictReader(fh))


def med(v):
    v = sorted(v)
    return R4.q(v, 0.5) if v else math.nan


def pct(x):
    """MPE in percent: two decimals below 10, one decimal below 100, otherwise an integer."""
    if x != x:
        return "--"
    if x < 10:
        return "%.2f" % x
    return "%.1f" % x if x < 99.95 else "%d" % round(x)


def half_up(x):
    """Round to an integer with halves away from zero (12.5 -> 13), as the text of the paper does."""
    return int(math.copysign(math.floor(abs(x) + 0.5), x))


def ci(t):
    d, lo, hi = t
    sign = lambda v: "0" if v == 0 else "%+d" % v                      # noqa: E731  (no signed zero)
    return "$%s$ [$%s$, $%s$]" % tuple(sign(half_up(100 * v)) for v in (d, lo, hi))


def write(name, body):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w") as fh:
        fh.write("% generated by script/diag/make_supp_tables.py -- do not edit by hand\n" + body)
    print("wrote %s" % _layout.rel(os.path.join(OUT, name)))


